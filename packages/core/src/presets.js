/**
 * Design presets. Every preset keeps strong contrast and a proper quiet zone,
 * so they all scan reliably out of the box.
 */
function collection(
  id,
  name,
  description,
  foreground,
  background,
  moduleStyle,
  cornerStyle,
  category,
  cornerColor = null,
  frame = null,
) {
  return {
    id,
    name,
    description,
    category,
    options: {
      foreground,
      background,
      moduleStyle,
      cornerStyle,
      cornerDotStyle: cornerStyle,
      cornerColor,
      frame,
    },
  };
}

